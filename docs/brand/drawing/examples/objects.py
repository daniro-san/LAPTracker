# ---------------- yarn ----------------
def yarn():
    cx, cy, r = 58, 71, 28
    P = lambda a, k=.97: (cx + r*k*math.cos(math.radians(a)), cy + r*k*math.sin(math.radians(a)))
    g = Path()
    stroke(g, arc(cx, cy, r, r, 235, 505, 10, wob=[0, .015, -.005, -.018, .004, .02, -.004, -.016, .006, 0]), 1.45, a=.12, b=.2)
    stroke(g, arc(cx, cy, r+.8, r+.8, 122, 250, 5), .75, a=.35, b=.4)
    # middle band: three wraps from upper right to lower left
    M = [quad(P(a0), P(a1), .1, 21, side=1) for a0, a1 in ((-66, 156), (-50, 140), (-34, 124))]
    for m in M:
        stroke(g, m[::4], .7, a=.2, b=.2)
    # upper-left cap: short wraps running into the band
    for a, t in ((190, 15), (218, 10), (248, 5)):
        stroke(g, quad(P(a), M[0][t], .1, 4, side=-1), .62, a=.3, b=.15)
    # lower-right cap: wraps hugging the contour, tucked under the band
    for a, t in ((-12, 7), (12, 12), (40, 16), (68, 19)):
        stroke(g, quad(P(a), M[2][t], .1, 4, side=1), .62, a=.3, b=.15)
    # needles
    stroke(g, [(46, 49), (34, 35), (22, 21)], .72, a=.05, b=.05, e=.55)
    blob(g, [(18.5, 19), (21, 16.5), (24, 18.5), (22.5, 22), (19.5, 21.8)])
    stroke(g, [(68, 46), (82, 30), (95, 15.5)], .72, a=.05, b=.05, e=.55)
    blob(g, [(94.5, 13), (97.5, 11), (100, 13.5), (98, 16.5), (95, 16)])
    # thread + floor (outside group)
    f = Path()
    stroke(f, [(70, 95), (84, 99.5), (100, 100), (114, 96), (121, 87), (116, 80.5), (109, 85), (113, 94),
               (126, 99.5), (140, 97), (151, 88), (161, 80)], .8, a=.06, b=0, e=.35)
    stroke(f, [(16, 100.5), (36, 100), (52, 100.6)], .65, a=.4, b=.3)
    stroke(f, [(24, 103.5), (34, 103.2)], .45, a=.5, b=.5)
    return svg(['<g data-anim="sway">', el(g), '</g>', el(f)])

